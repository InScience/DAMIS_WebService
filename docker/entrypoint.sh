#!/bin/bash
# Generates the DamisService configuration from environment variables, then starts Apache.
#
#   SERVICE_URL         public URL of the CGI, written into the WSDL (soap:address)
#   DATA_URL            public URL of the result files directory (Y = DATA_URL + _output_*.arff)
#   MPI_PROCESSES       maximum processes per algorithm run, the "p" request parameter (default: CPU count)
#   MPI_OPTIONS         extra mpirun options
#   MAX_RUN_TIME        seconds after which an algorithm run is killed (keep below Apache Timeout 3600)
#   KEEP_FILES_SECONDS  data files older than this are deleted on the next request (default 2 days)
set -euo pipefail

SERVICE_URL="${SERVICE_URL:-http://localhost/cgi-bin/DamisService.cgi}"
DATA_URL="${DATA_URL:-http://localhost/DamisData/}"
[[ "$DATA_URL" == */ ]] || DATA_URL="$DATA_URL/"
MPI_PROCESSES="${MPI_PROCESSES:-$(nproc)}"
MPI_OPTIONS="${MPI_OPTIONS:---oversubscribe --bind-to none}"
MAX_RUN_TIME="${MAX_RUN_TIME:-3300}"
KEEP_FILES_SECONDS="${KEEP_FILES_SECONDS:-172800}"

CGI_DIR=/usr/lib/cgi-bin
DATA_DIR=/var/lib/damis/data/
LOG_DIR=/var/log/damis

mkdir -p /etc/damis "${DATA_DIR}err" "$LOG_DIR"
chown www-data:www-data "$DATA_DIR" "${DATA_DIR}err" "$LOG_DIR"

# WSDL served on ?wsdl, with the address clients have to call
sed "s#<SOAP:address location=\"[^\"]*\"#<SOAP:address location=\"${SERVICE_URL}\"#" \
    /usr/share/damis/damis.wsdl > /etc/damis/damis.wsdl

# easylogging++ 9.x; never TO_STANDARD_OUTPUT (stdout is the SOAP response)
cat > /etc/damis/logging.conf <<EOF
* GLOBAL:
    FORMAT = "%datetime %level %msg"
    FILENAME = "${LOG_DIR}/damis-service.log"
    ENABLED = true
    TO_FILE = true
    TO_STANDARD_OUTPUT = false
    MAX_LOG_FILE_SIZE = 10485760
EOF

# read by DamisService.cgi from its own directory
cat > "$CGI_DIR/settings.csv" <<EOF
% generated by damis-entrypoint from environment variables at container start - do not edit
wsdlPath /etc/damis/damis.wsdl
logingConfFilePath /etc/damis/logging.conf
pathToAlgorithmsExe /opt/damis/bin/Algorithms
pathToMPIExecutable mpirun
mpiOptions ${MPI_OPTIONS}
noOfProcessors ${MPI_PROCESSES}
maxRunTime ${MAX_RUN_TIME}
localDataFileSavePath ${DATA_DIR}
workingDirMPI ${DATA_DIR}
httpDataFileSavePath ${DATA_URL}
dataFileExtension .arff
lenghtOfTmpFileName 20
keepFilesInDirectory ${KEEP_FILES_SECONDS}
EOF
chmod 644 "$CGI_DIR/settings.csv" /etc/damis/damis.wsdl /etc/damis/logging.conf

echo "damis-service: SOAP endpoint ${SERVICE_URL}, results ${DATA_URL}, up to ${MPI_PROCESSES} MPI processes, run limit ${MAX_RUN_TIME}s"

exec "$@"
